package kadx.tests.integration.inline

import kadx.core.dex.nodes.MethodNode
import kadx.tests.api.IntegrationTest
import kadx.tests.api.extensions.profiles.TestProfile
import kadx.tests.api.extensions.profiles.TestWithProfiles
import kadx.tests.api.utils.assertj.KadxAssertions.assertThat
import org.assertj.core.api.Condition
import org.junit.jupiter.api.Test

/**
 * 泛型内部类的 bridge 方法：`IntInner.get` 不应被重命名（如 `mo0get`），调用点保持 `get`。
 */
class TestSyntheticBridgeRename : IntegrationTest() {

	@TestWithProfiles(TestProfile.DX_J8, TestProfile.JAVA8)
	fun test() {
		val cls = getClassNode(TestSyntheticBridgeRenameFixture.TestCls::class.java)
		assertThat(searchCls(cls.innerClasses, "IntInner").methods)
			.`as`("check that bridge method was generated by compiler")
			.haveAtLeastOne(Condition<MethodNode>({ mth -> mth.accessFlags.isBridge() }, "bridge"))

		assertThat(cls)
			.code()
			.doesNotContain("mo0get")
			.containsOne("call(inner.get(\"a\"));")
	}
}
