/**
 * 由 JFlex 生成的 Smali 词法分析器（lexer）。
 *
 * **做什么**：把 Smali 源码切分成带类型的 token（关键字、标识符、数字、字符串、
 * 注释等），供 RSyntaxTextArea 做语法高亮。核心是 `yylex()` 状态机与几张压缩表。
 *
 * **为什么保留生成风格**：这是自动生成的代码，逻辑与表结构一一对应；
 * 手写重构极易破坏状态机，因此只做 Java→Kotlin 的机械转换。
 *
 * **Kotlin 说明**：Java 的八进制转义 `\NNN` 在 Kotlin 中不支持，
 * 打包字符串已统一改写为 `\uXXXX`。
 */
@Suppress("unused", "MemberVisibilityCanBePrivate", "RedundantVisibilityModifier")
class SmaliTokenMaker : AbstractJFlexCTokenMaker {

	/** 输入设备 */
	private var zzReader: Reader? = null

	/** DFA 的当前状态 */
	private var zzState = 0

	/** 当前词法状态 */
	private var zzLexicalState = YYINITIAL

	/** 当前待匹配文本所在的缓冲区（即 yytext() 的来源） */
	private lateinit var zzBuffer: CharArray

	/** 最后一个接受状态对应的文本位置 */
	private var zzMarkedPos = 0

	/** 最后一次被包含进 yytext 的状态对应的文本位置 */
	private var zzPushbackPos = 0

	/** 缓冲区中的当前文本位置 */
	private var zzCurrentPos = 0

	/** yytext() 字符串在缓冲区中的起始位置 */
	private var zzStartRead = 0

	/** 从输入中读取到的缓冲区最后一个字符位置 */
	private var zzEndRead = 0

	/** 匹配文本开始前遇到的换行数 */
	private var yyline = 0

	/** 匹配文本开始前的字符数 */
	private var yychar = 0

	/** 从上一个换行到匹配文本开始之间的字符数 */
	private var yycolumn = 0

	/** zzAtBOL == true 表示扫描器当前位于行首 */
	private var zzAtBOL = true

	/** zzAtEOF == true 表示扫描器已到文件末尾 */
	private var zzAtEOF = false

	/**
	 * 无参构造器。JFlex 不会生成无参构造器，因此必须在这里提供。
	 */
	constructor() : super()

	/**
	 * 创建扫描器（Reader 版本）。
	 */
	constructor(inReader: Reader) : super() {
		this.zzReader = inReader
	}

	/**
	 * 创建扫描器（InputStream 版本）。
	 */
	constructor(inputStream: InputStream) : this(InputStreamReader(inputStream))

	/**
	 * 把指定 token 加入当前 token 链表。
	 */
	private fun addHyperlinkToken(start: Int, end: Int, tokenType: Int) {
		val so = start + offsetShift
		addToken(zzBuffer, start, end, tokenType, so, true)
	}

	/**
	 * 把指定 token 加入当前 token 链表。
	 */
	private fun addToken(tokenType: Int) {
		addToken(zzStartRead, zzMarkedPos - 1, tokenType)
	}

	/**
	 * 把指定 token 加入当前 token 链表。
	 */
	private fun addToken(start: Int, end: Int, tokenType: Int) {
		val so = start + offsetShift
		addToken(zzBuffer, start, end, tokenType, so, false)
	}

	/**
	 * 把指定 token 加入当前 token 链表（覆写父类）。
	 */
	override fun addToken(array: CharArray, start: Int, end: Int, tokenType: Int, startOffset: Int, hyperlink: Boolean) {
		super.addToken(array, start, end, tokenType, startOffset, hyperlink)
		zzStartRead = zzMarkedPos
	}

	/**
	 * 返回行注释的开始与结束标记。
	 */
	override fun getLineCommentStartAndEnd(languageIndex: Int): Array<String?> = arrayOf("#", null)

	/**
	 * 重新填充输入缓冲区。
	 */
	private fun zzRefill(): Boolean = zzCurrentPos >= s.offset + s.count

	/**
	 * 重置扫描器以从新的输入流读取，不会关闭旧 reader。
	 */
	fun yyreset(reader: Reader?) {
		// 's' 已经更新
		zzBuffer = s.array
		zzStartRead = s.offset
		zzEndRead = zzStartRead + s.count - 1
		zzCurrentPos = s.offset
		zzMarkedPos = zzCurrentPos
		zzPushbackPos = zzCurrentPos
		zzLexicalState = YYINITIAL
		zzReader = reader
		zzAtBOL = true
		zzAtEOF = false
	}

	/**
	 * 关闭输入流。
	 */
	@Throws(IOException::class)
	override fun yyclose() {
		zzAtEOF = true // 标记文件结束
		zzEndRead = zzStartRead // 使缓冲区失效
		zzReader?.close()
	}

	/**
	 * 进入新的词法状态。
	 */
	override fun yybegin(newState: Int) {
		zzLexicalState = newState
	}

	override fun yystate(): Int = zzLexicalState

	/**
	 * 返回当前正则表达式匹配到的文本。
	 */
	override fun yytext(): String = String(zzBuffer, zzStartRead, zzMarkedPos - zzStartRead)

	/**
	 * 返回匹配文本中位置 pos 处的字符。
	 */
	override fun yycharat(pos: Int): Char = zzBuffer[zzStartRead + pos]

	/**
	 * 返回匹配文本的长度。
	 */
	override fun yylength(): Int = zzMarkedPos - zzStartRead

	/**
	 * 报告扫描过程中出现的错误。
	 */
	private fun zzScanError(errorCode: Int) {
		val message: String = try {
			ZZ_ERROR_MSG[errorCode]
		} catch (e: ArrayIndexOutOfBoundsException) {
			ZZ_ERROR_MSG[ZZ_UNKNOWN_ERROR]
		}
		throw Error(message)
	}

	/**
	 * 把指定数量的字符推回输入流，它们会在下一次扫描时被重新读取。
	 */
	override fun yypushback(number: Int) {
		if (number > yylength()) {
			zzScanError(ZZ_PUSHBACK_2BIG)
		}
		zzMarkedPos -= number
	}

	/**
	 * 获取指定文本的 token 链表首节点。
	 */
	override fun getTokenList(text: Segment, initialTokenType: Int, startOffset: Int): Token? {
		resetTokenList()
		this.offsetShift = -text.offset + startOffset

		// 从正确的状态开始
		val state = Token.NULL

		s = text
		return try {
			yyreset(zzReader)
			yybegin(state)
			yylex()
		} catch (ioe: IOException) {
			ioe.printStackTrace()
			TokenImpl()
		}
	}

	/**
	 * 持续扫描直到匹配到下一个正则、遇到输入结束或发生 IO 错误。
	 *
	 * @return 下一个 token
	 */
	@Throws(IOException::class)
	fun yylex(): Token? {
		var zzInput = YYEOF
		var zzAction: Int

		// 缓存字段：
		var zzCurrentPosL: Int
		var zzMarkedPosL: Int
		var zzEndReadL = zzEndRead
		var zzBufferL = zzBuffer
		val zzCMapL = ZZ_CMAP

		val zzTransL = ZZ_TRANS
		val zzRowMapL = ZZ_ROWMAP
		val zzAttrL = ZZ_ATTRIBUTE

		while (true) {
			zzMarkedPosL = zzMarkedPos

			zzAction = -1

			zzCurrentPosL = zzMarkedPosL
			zzCurrentPos = zzCurrentPosL
			zzStartRead = zzCurrentPosL

			zzState = zzLexicalState

			run zzForAction@{
				while (true) {
					if (zzCurrentPosL < zzEndReadL) {
						zzInput = zzBufferL[zzCurrentPosL++].code
					} else if (zzAtEOF) {
						zzInput = YYEOF
						return@zzForAction
					} else {
						// 回存缓存位置
						zzCurrentPos = zzCurrentPosL
						zzMarkedPos = zzMarkedPosL
						val eof = zzRefill()
						// 重新取得翻译后的位置，缓冲可能已变化
						zzCurrentPosL = zzCurrentPos
						zzMarkedPosL = zzMarkedPos
						zzBufferL = zzBuffer
						zzEndReadL = zzEndRead
						if (eof) {
							zzInput = YYEOF
							return@zzForAction
						} else {
							zzInput = zzBufferL[zzCurrentPosL++].code
						}
					}
					val zzNext = zzTransL[zzRowMapL[zzState] + zzCMapL[zzInput].code]
					if (zzNext == -1) {
						return@zzForAction
					}
					zzState = zzNext

					val zzAttributes = zzAttrL[zzState]
					if ((zzAttributes and 1) == 1) {
						zzAction = zzState
						zzMarkedPosL = zzCurrentPosL
						if ((zzAttributes and 8) == 8) {
							return@zzForAction
						}
					}
				}
			}

			// 回存缓存位置
			zzMarkedPos = zzMarkedPosL

			when (if (zzAction < 0) zzAction else ZZ_ACTION[zzAction]) {
				4 -> {
					addNullToken()
					return firstToken
				}

				19 -> addToken(Token.LITERAL_CHAR)

				26 -> addToken(Token.MARKUP_TAG_NAME)

				7 -> addToken(Token.WHITESPACE)

				18 -> addToken(Token.LITERAL_NUMBER_HEXADECIMAL)

				21 -> addToken(Token.ERROR_STRING_DOUBLE)

				17 -> addToken(Token.LITERAL_NUMBER_FLOAT)

				22 -> addToken(Token.RESERVED_WORD)

				8 -> addToken(Token.SEPARATOR)

				10 -> addToken(Token.VARIABLE)

				1 -> addToken(Token.IDENTIFIER)

				13 -> {
					addToken(start, zzStartRead - 1, Token.COMMENT_EOL)
					addNullToken()
					return firstToken
				}

				20 -> addToken(Token.FUNCTION)

				3 -> {
					addToken(Token.ERROR_CHAR)
					addNullToken()
					return firstToken
				}

				5 -> {
					addToken(Token.ERROR_STRING_DOUBLE)
					addNullToken()
					return firstToken
				}

				11 -> addToken(Token.DATA_TYPE)

				15 -> addToken(Token.ERROR_CHAR)

				23 -> addToken(Token.LITERAL_BOOLEAN)

				16 -> addToken(Token.LITERAL_STRING_DOUBLE_QUOTE)

				24 -> {
					val temp = zzStartRead
					addToken(start, zzStartRead - 1, Token.COMMENT_EOL)
					addHyperlinkToken(temp, zzMarkedPos - 1, Token.COMMENT_EOL)
					start = zzMarkedPos
				}

				25 -> addToken(Token.RESERVED_WORD_2)

				14 -> addToken(Token.ERROR_NUMBER_FORMAT)

				6 -> {
					start = zzMarkedPos - 1
					yybegin(EOL_COMMENT)
				}

				2 -> addToken(Token.LITERAL_NUMBER_DECIMAL_INT)

				9 -> addToken(Token.OPERATOR)

				12 -> {
				}

				else -> {
					if (zzInput == YYEOF && zzStartRead == zzCurrentPos) {
						zzAtEOF = true
						when (zzLexicalState) {
							EOL_COMMENT -> {
								addToken(start, zzStartRead - 1, Token.COMMENT_EOL)
								addNullToken()
								return firstToken
							}

							702 -> {
							}

							YYINITIAL -> {
								addNullToken()
								return firstToken
							}

							703 -> {
							}

							else -> return null
						}
					} else {
						zzScanError(ZZ_NO_MATCH)
					}
				}
			}
		}
	}

